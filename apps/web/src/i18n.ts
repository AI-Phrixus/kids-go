export function t(
  locale: Locale,
  key: string,
  vars?: {
    name?: string;
    n?: number | string;
    cur?: number | string;
    total?: number | string;
    need?: number | string;
    url?: string;
  },
): string {
  const raw = dict[locale]?.[key] ?? dict.en[key] ?? key;
  return raw
    .replaceAll("{{name}}", vars?.name?.trim() || fallbackName(locale))
    .replaceAll("{{n}}", String(vars?.n ?? ""))
    .replaceAll("{{cur}}", String(vars?.cur ?? ""))
    .replaceAll("{{total}}", String(vars?.total ?? ""))
    .replaceAll("{{need}}", String(vars?.need ?? ""))
    .replaceAll("{{url}}", vars?.url ?? "");
}

export function fallbackName(locale: Locale): string {
  if (locale === "ja") return "きみ";
  if (locale === "zh-Hant") return "小朋友";
  return "friend";
}

export function pickLocaleText(
  locale: Locale,
  obj: Record<string, string> | undefined,
  name?: string,
): string {
  if (!obj) return "";
  const raw = obj[locale] ?? obj.en ?? obj.ja ?? Object.values(obj)[0] ?? "";
  return raw.replaceAll("{{name}}", name?.trim() || fallbackName(locale));
}
